class Translator:
    """Penerjemah kunci -> teks. Bahasa default English, fallback ke English."""

    def __init__(self, lang: str = DEFAULT_LANG) -> None:
        self._lang = lang if lang in TRANSLATIONS else DEFAULT_LANG

    @property
    def lang(self) -> str:
        return self._lang

    def set_lang(self, lang: str) -> bool:
        """Kembalikan True kalau bahasa benar-benar berubah."""
        if lang not in TRANSLATIONS or lang == self._lang:
            return False
        self._lang = lang
        return True

    def toggle(self) -> str:
        order = list(LANGUAGES)
        nxt = order[(order.index(self._lang) + 1) % len(order)]
        self._lang = nxt
        return nxt

    def lang_name(self, lang: str = "") -> str:
        return LANGUAGE_NAMES.get(lang or self._lang, "English")

    def __call__(self, key: str, **kwargs: Any) -> str:
        table = TRANSLATIONS.get(self._lang, TRANSLATIONS[DEFAULT_LANG])
        text = table.get(key)
        if text is None:
            text = TRANSLATIONS[DEFAULT_LANG].get(key, f"??{key}??")
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                return text
        return text

    get = __call__


t = Translator()


def set_language(lang: str) -> bool:
    return t.set_lang(lang)


def all_keys() -> set:
    return set(TRANSLATIONS[DEFAULT_LANG])


def missing_keys() -> Dict[str, list]:
    """Kunci yang belum ada di salah satu bahasa (dipakai untuk validasi)."""
    base = all_keys()
    out: Dict[str, list] = {}
    for lang, table in TRANSLATIONS.items():
        gap = sorted(base - set(table))
        if gap:
            out[lang] = gap
    return out
